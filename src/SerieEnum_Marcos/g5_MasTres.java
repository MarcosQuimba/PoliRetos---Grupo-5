package SerieEnum_Marcos;

public class g5_MasTres {
    public void MostrarMasTres() {
        System.out.println("Serie de Mas Tres:");
        int num = 1;
        for (int i = 0; i < 10; i++) {
            System.out.print(num + " ");
            num += 3;
        }
        System.out.println();
    }
}
